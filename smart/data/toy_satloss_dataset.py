"""Dataset adapter for the self-generated SATLOSS sampling benchmark.

The benchmark intentionally separates the *native encoder cloud* from the
uniformly sampled surface/volume supervision clouds.  Consequently, a model
can only solve the task robustly if it does not tie the learned operator to a
particular source-point density.
"""

from __future__ import annotations

import json
from collections import OrderedDict
from multiprocessing import Value
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset

try:
    from utils.geometry_density import estimate_log_sampling_density
except ImportError:  # pragma: no cover
    from smart.utils.geometry_density import estimate_log_sampling_density


class ToySATLossDataset(Dataset):
    """Read deterministic analytic-geometry cases generated by the toy script."""

    CACHE_VERSION = "toy_satloss_poisson_train_stats_v2"
    SURFACE_FIELDS = ("manufactured_surface",)
    VOLUME_FIELDS = ("manufactured_volume",)

    def __init__(
        self,
        saved_folder,
        if_test=False,
        geometry_points=8192,
        surface_points=8192,
        volume_points=8192,
        scale_positions=False,
        coordinate_normalization="global_train_bounds",
        split_seed=42,
        geometry_epoch_seeded_sampling=True,
        return_geometry_density=False,
        geometry_density_knn_k=16,
        geometry_density_neighbor_hops=1,
        geometry_density_estimator="kde",
        geometry_density_cache_dtype="float16",
        **_unused,
    ):
        del scale_positions
        self.root = Path(saved_folder).expanduser().resolve()
        self.if_test = bool(if_test)
        self.geometry_points = int(geometry_points)
        self.surface_points = int(surface_points)
        self.volume_points = int(volume_points)
        self.geometry_epoch_seeded_sampling = bool(geometry_epoch_seeded_sampling)
        self.return_geometry_density = bool(return_geometry_density)
        self.geometry_density_knn_k = max(1, int(geometry_density_knn_k))
        self.geometry_density_neighbor_hops = max(0, int(geometry_density_neighbor_hops))
        self.geometry_density_estimator = str(geometry_density_estimator)
        self.geometry_density_cache_dtype = str(geometry_density_cache_dtype)
        self.split_seed = int(split_seed)
        self._shared_epoch = Value("i", 0, lock=False)
        self._arrays = OrderedDict()
        self._density = OrderedDict()
        self._cache_size = 8
        if str(coordinate_normalization).lower() not in {"global_train_bounds", "global_bounds"}:
            raise ValueError("ToySATLoss requires global_train_bounds coordinate normalization.")
        if not self.root.is_dir():
            raise FileNotFoundError(f"ToySATLoss root does not exist: {self.root}")

        manifest_path = self.root / "preprocessed_manifest.json"
        if not manifest_path.is_file():
            raise FileNotFoundError(f"Missing manifest: {manifest_path}")
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        self.training_ids = tuple(int(x) for x in manifest["train_ids"])
        self.test_ids = tuple(int(x) for x in manifest["validation_ids"])
        self.data = self.test_ids if self.if_test else self.training_ids
        if not self.data:
            raise ValueError("ToySATLoss selected split is empty.")
        self.surface_field_names = list(self.SURFACE_FIELDS)
        self.volume_field_names = list(self.VOLUME_FIELDS)
        self._load_train_statistics()
        print(
            f"[ToySATLoss] split={'validation' if self.if_test else 'train'}, cases={len(self.data)}, "
            f"geometry_points={'full' if self.geometry_points == 0 else self.geometry_points}, "
            f"surface_queries={self.surface_points}, volume_queries={self.volume_points}, "
            f"density={self.return_geometry_density}"
        )

    def _run_dir(self, case_id):
        return self.root / f"case_{int(case_id):05d}"

    def _stats_paths(self):
        return (
            self.root / f"surface_stats_{self.CACHE_VERSION}.npy",
            self.root / f"volume_stats_{self.CACHE_VERSION}.npy",
            self.root / f"position_stats_{self.CACHE_VERSION}.npy",
        )

    def _load_train_statistics(self):
        surface_path, volume_path, position_path = self._stats_paths()
        if not (surface_path.is_file() and volume_path.is_file() and position_path.is_file()):
            surface_sum = surface_sq_sum = volume_sum = volume_sq_sum = 0.0
            surface_count = volume_count = 0
            pos_min = np.full(3, np.inf, dtype=np.float64)
            pos_max = np.full(3, -np.inf, dtype=np.float64)
            for case_id in self.training_ids:
                meta = json.loads((self._run_dir(case_id) / "case_metadata.json").read_text(encoding="utf-8"))
                surface_sum += float(meta["surface_sum"])
                surface_sq_sum += float(meta["surface_sq_sum"])
                volume_sum += float(meta["volume_sum"])
                volume_sq_sum += float(meta["volume_sq_sum"])
                surface_count += int(meta["surface_count"])
                volume_count += int(meta["volume_count"])
                pos_min = np.minimum(pos_min, np.asarray(meta["position_min"], dtype=np.float64))
                pos_max = np.maximum(pos_max, np.asarray(meta["position_max"], dtype=np.float64))
            def stats(total, total_sq, count):
                mean = total / max(count, 1)
                var = max((total_sq - total * total / max(count, 1)) / max(count - 1, 1), 1.0e-12)
                return np.asarray([mean, np.sqrt(var)], dtype=np.float32)
            np.save(surface_path, stats(surface_sum, surface_sq_sum, surface_count), allow_pickle=False)
            np.save(volume_path, stats(volume_sum, volume_sq_sum, volume_count), allow_pickle=False)
            np.save(position_path, np.stack([pos_min, pos_max]).astype(np.float32), allow_pickle=False)
        self.mean_surf_data = torch.from_numpy(np.asarray(np.load(surface_path)[0:1], dtype=np.float32))
        self.std_surf_data = torch.from_numpy(np.maximum(np.asarray(np.load(surface_path)[1:2], dtype=np.float32), 1.0e-12))
        self.mean_vol_data = torch.from_numpy(np.asarray(np.load(volume_path)[0:1], dtype=np.float32))
        self.std_vol_data = torch.from_numpy(np.maximum(np.asarray(np.load(volume_path)[1:2], dtype=np.float32), 1.0e-12))
        bounds = np.asarray(np.load(position_path), dtype=np.float32)
        self.min_pos = torch.from_numpy(bounds[0])
        self.position_span = torch.from_numpy(np.maximum(bounds[1] - bounds[0], 1.0e-12))

    def _get_arrays(self, case_id):
        case_id = int(case_id)
        arrays = self._arrays.get(case_id)
        if arrays is None:
            run_dir = self._run_dir(case_id)
            arrays = {key: np.load(run_dir / f"{key}.npy", mmap_mode="r") for key in (
                "geometry_coords", "surface_coords", "surface_data", "volume_coords", "volume_data"
            )}
            self._arrays[case_id] = arrays
        self._arrays.move_to_end(case_id)
        while len(self._arrays) > self._cache_size:
            self._arrays.popitem(last=False)
        return arrays

    def _density_path(self, case_id):
        return self._run_dir(case_id) / (
            f"geometry_log_density_k{self.geometry_density_knn_k}_{self.geometry_density_estimator}.npy"
        )

    def _load_density(self, case_id, coords):
        case_id = int(case_id)
        value = self._density.get(case_id)
        if value is None:
            path = self._density_path(case_id)
            if path.is_file():
                value = torch.from_numpy(np.array(np.load(path, mmap_mode="r"), dtype=np.float32, copy=True))
            else:
                raw = np.asarray(coords, dtype=np.float32)
                norm = (raw - raw.min(0)) / np.maximum(raw.max(0) - raw.min(0), 1.0e-12)
                norm = np.clip(norm, 0.0, 1.0 - 1.0e-6)
                value = estimate_log_sampling_density(
                    torch.from_numpy(norm).unsqueeze(0),
                    knn_k=self.geometry_density_knn_k,
                    neighbor_hops=self.geometry_density_neighbor_hops,
                    estimator=self.geometry_density_estimator,
                ).squeeze(0).cpu().float()
            self._density[case_id] = value
        self._density.move_to_end(case_id)
        while len(self._density) > self._cache_size:
            self._density.popitem(last=False)
        return value

    def set_epoch(self, epoch):
        self._shared_epoch.value = int(epoch)

    def __len__(self):
        return len(self.data)

    def _rng(self, case_id, stream):
        if self.geometry_epoch_seeded_sampling:
            return np.random.default_rng(np.random.SeedSequence([self.split_seed, self._shared_epoch.value, int(case_id), stream]))
        return np.random.default_rng()

    @staticmethod
    def _sample(count, budget, rng):
        if budget <= 0 or budget >= count:
            return np.arange(count, dtype=np.int64)
        return rng.choice(count, size=budget, replace=False).astype(np.int64, copy=False)

    def __getitem__(self, index):
        case_id = int(self.data[index])
        arrays = self._get_arrays(case_id)
        ng, ns, nv = (
            int(arrays["geometry_coords"].shape[0]),
            int(arrays["surface_coords"].shape[0]),
            int(arrays["volume_coords"].shape[0]),
        )
        geo_idx = self._sample(ng, self.geometry_points, self._rng(case_id, 0))
        surf_idx = self._sample(ns, self.surface_points, self._rng(case_id, 1))
        vol_idx = self._sample(nv, self.volume_points, self._rng(case_id, 2))
        def norm(x):
            return (np.asarray(x, dtype=np.float32) - self.min_pos.numpy()) / self.position_span.numpy()
        result = (
            torch.from_numpy(np.array(norm(arrays["geometry_coords"][geo_idx]), copy=True)),
            torch.from_numpy(np.array(norm(arrays["surface_coords"][surf_idx]), copy=True)),
            torch.from_numpy(np.array((np.asarray(arrays["surface_data"][surf_idx], dtype=np.float32) - self.mean_surf_data.numpy()) / self.std_surf_data.numpy(), copy=True)),
            torch.from_numpy(np.array(norm(arrays["volume_coords"][vol_idx]), copy=True)),
            torch.from_numpy(np.array((np.asarray(arrays["volume_data"][vol_idx], dtype=np.float32) - self.mean_vol_data.numpy()) / self.std_vol_data.numpy(), copy=True)),
        )
        if not self.return_geometry_density:
            return result
        density = self._load_density(case_id, arrays["geometry_coords"]).index_select(0, torch.from_numpy(geo_idx))
        return result + (density.contiguous(),)
